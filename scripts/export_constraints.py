"""Export the installed dependency closure for SnowLabel's direct requirements."""

from __future__ import annotations

import argparse
import importlib.metadata as metadata
import platform
import sys
import tomllib
from collections import deque
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent


def requirement_lines(path: Path) -> list[str]:
    lines = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith(("#", "-")):
            lines.append(line)
    return lines


def marker_applies(req: Requirement, extras: frozenset[str]) -> bool:
    if req.marker is None:
        return True
    env = default_environment()
    return any(
        req.marker.evaluate({**env, "extra": extra})
        for extra in ({"", *extras})
    )


def installed_distributions() -> dict[str, metadata.Distribution]:
    return {
        canonicalize_name(dist.metadata["Name"]): dist
        for dist in metadata.distributions()
        if dist.metadata.get("Name")
    }


def dependency_closure(
    requirements_path: Path,
    pyproject_path: Path,
) -> list[metadata.Distribution]:
    installed = installed_distributions()
    queue: deque[tuple[str, frozenset[str]]] = deque()
    pyproject = tomllib.loads(pyproject_path.read_text(encoding="utf-8"))
    dev_requirements = pyproject["project"]["optional-dependencies"].get("dev", [])
    for line in [*requirement_lines(requirements_path), *dev_requirements]:
        req = Requirement(line)
        queue.append((canonicalize_name(req.name), frozenset(req.extras)))

    selected: dict[str, metadata.Distribution] = {}
    seen_states: set[tuple[str, frozenset[str]]] = set()
    while queue:
        name, extras = queue.popleft()
        state = (name, extras)
        if state in seen_states:
            continue
        seen_states.add(state)
        dist = installed.get(name)
        if dist is None:
            raise RuntimeError(f"Required distribution is not installed: {name}")
        selected[name] = dist
        for raw in dist.requires or []:
            req = Requirement(raw)
            if marker_applies(req, extras):
                queue.append((canonicalize_name(req.name), frozenset(req.extras)))
    return [selected[name] for name in sorted(selected)]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--requirements",
        type=Path,
        default=ROOT / "requirements.txt",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "constraints" / "windows-py311-cu121.txt",
    )
    args = parser.parse_args()

    distributions = dependency_closure(args.requirements, ROOT / "pyproject.toml")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    header = [
        "# Generated by scripts/export_constraints.py from the verified v0.1 environment.",
        f"# Python {platform.python_version()} on {platform.platform()}",
        "# PyTorch CUDA 12.1 wheels are resolved from the official PyTorch index.",
        "--extra-index-url https://download.pytorch.org/whl/cu121",
        "",
    ]
    pins = [f"{dist.metadata['Name']}=={dist.version}" for dist in distributions]
    args.output.write_text("\n".join(header + pins) + "\n", encoding="utf-8")
    print(f"wrote {len(pins)} pins to {args.output}")


if __name__ == "__main__":
    sys.exit(main())
